import { randomBytes } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * File storage behind one interface. Today: local disk under public/uploads.
 * Moving to S3 / Cloudflare R2 = one new class implementing FileStorage (e.g. with
 * @aws-sdk/client-s3 — R2 speaks the S3 API) and a switch in storage(); callers only
 * ever see keys and public URLs, and the DB stores URLs, so nothing else changes.
 */

export interface StoredFile {
  /** Provider-neutral path, e.g. "products/2026/11/k3j9x2m4q1ab.webp". */
  key: string;
  /** What to save in the database and put in <img src>. */
  url: string;
  contentType: string;
  size: number;
}

export interface FileStorage {
  put(key: string, body: Uint8Array, contentType: string): Promise<StoredFile>;
  /** Local provider only (S3/R2 serve files themselves); null when missing. */
  get(key: string): Promise<{ body: Uint8Array<ArrayBuffer>; contentType: string } | null>;
  delete(key: string): Promise<void>;
  publicUrl(key: string): string;
}

export const IMAGE_TYPES = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "image/avif": "avif",
} as const;
export type ImageType = keyof typeof IMAGE_TYPES;
const TYPE_BY_EXT: Record<string, ImageType> = { jpg: "image/jpeg", png: "image/png", webp: "image/webp", avif: "image/avif" };

/** Keys are generated by us; still, refuse anything that could escape the folder. */
function assertSafeKey(key: string): void {
  if (!/^[a-z0-9][a-z0-9/_-]*\.[a-z0-9]+$/.test(key) || key.includes("..") || key.includes("//")) {
    throw new Error(`Unsafe storage key: ${key}`);
  }
}

class LocalDiskStorage implements FileStorage {
  constructor(
    private readonly root: string,
    private readonly urlPrefix: string,
  ) {}

  private file(key: string): string {
    assertSafeKey(key);
    return path.join(this.root, ...key.split("/"));
  }

  async put(key: string, body: Uint8Array, contentType: string): Promise<StoredFile> {
    const file = this.file(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, body, { flag: "wx" }); // never overwrite
    return { key, url: this.publicUrl(key), contentType, size: body.byteLength };
  }

  async get(key: string): Promise<{ body: Uint8Array<ArrayBuffer>; contentType: string } | null> {
    try {
      const ext = key.slice(key.lastIndexOf(".") + 1);
      const contentType = TYPE_BY_EXT[ext];
      if (!contentType) return null;
      return { body: new Uint8Array(await readFile(this.file(key))), contentType };
    } catch {
      return null;
    }
  }

  async delete(key: string): Promise<void> {
    await unlink(this.file(key)).catch((err: NodeJS.ErrnoException) => {
      if (err.code !== "ENOENT") throw err;
    });
  }

  publicUrl(key: string): string {
    return `${this.urlPrefix}/${key}`;
  }
}

let instance: FileStorage | null = null;

export function storage(): FileStorage {
  // Future: if (process.env.STORAGE_DRIVER === "r2") return new S3Storage({ bucket, endpoint, publicBaseUrl });
  instance ??= new LocalDiskStorage(process.env.UPLOADS_DIR ?? path.join(process.cwd(), "public", "uploads"), "/uploads");
  return instance;
}

/** Detects the real image type from the first bytes — the browser-sent type and file name are not trusted. */
export function sniffImageType(bytes: Uint8Array): ImageType | null {
  const b = bytes;
  if (b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "image/jpeg";
  if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47) return "image/png";
  const ascii = (from: number, to: number) => String.fromCharCode(...b.subarray(from, to));
  if (ascii(0, 4) === "RIFF" && ascii(8, 12) === "WEBP") return "image/webp";
  if (ascii(4, 8) === "ftyp" && ["avif", "avis"].includes(ascii(8, 12))) return "image/avif";
  return null;
}

/** "products/2026/11/<random>.webp" */
export function newImageKey(folder: string, type: ImageType, now = new Date()): string {
  const month = String(now.getUTCMonth() + 1).padStart(2, "0");
  return `${folder}/${now.getUTCFullYear()}/${month}/${randomBytes(9).toString("base64url").toLowerCase().replace(/[^a-z0-9]/g, "x")}.${IMAGE_TYPES[type]}`;
}
